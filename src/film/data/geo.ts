/**
 * The claimed Antarctic sector (25°W–74°W, south of 60°S) cannot be drawn in
 * Mercator. It is shown as an explicitly separated inset below Tierra del
 * Fuego: an azimuthal sketch centred on the pole, rotated so the sector's
 * bisector (49.5°W) points north toward the mainland. Scale is symbolic.
 */
export const ANTARCTIC_INSET = {
  pole: [M(49.5, 55)[0], M(49.5, 55)[1] + 1420] as Point,
  radiusPerDeg: 44,
};

export const antarctic = (lonW: number, latS: number): Point => {
  const r = (90 - latS) * ANTARCTIC_INSET.radiusPerDeg;
  const a = ((lonW - 49.5) * Math.PI) / 180;
  return [ANTARCTIC_INSET.pole[0] - Math.sin(a) * r, ANTARCTIC_INSET.pole[1] - Math.cos(a) * r];
};

