/** Voronoi cells of the capitals (world units), clipped later to the territory. */
export const regionCells = (): { id: string; c: Point; poly: Point[] }[] => {
  const pts = CAPITALS.filter((c) => c.id !== "parana").map((c) => ({ id: c.id, c: MP(c.ll) }));
  const box: Point[] = [M(72, 20), M(53, 20), M(53, 38), M(72, 38)];
  return pts.map((a) => {
    let poly = box;
    for (const b of pts) {
      if (b === a) {
        continue;
      }
      const mx = (a.c[0] + b.c[0]) / 2;
      const my = (a.c[1] + b.c[1]) / 2;
      const nx = b.c[0] - a.c[0];
      const ny = b.c[1] - a.c[1];
      const inside = (p: Point) => (p[0] - mx) * nx + (p[1] - my) * ny <= 0;
      const out: Point[] = [];
      for (let i = 0; i < poly.length; i++) {
        const p = poly[i];
        const q = poly[(i + 1) % poly.length];
        const ip = inside(p);
        const iq = inside(q);
        if (ip) {
          out.push(p);
        }
        if (ip !== iq) {
          const dp = (p[0] - mx) * nx + (p[1] - my) * ny;
          const dq = (q[0] - mx) * nx + (q[1] - my) * ny;
          const t = dp / (dp - dq);
          out.push([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t]);
        }
      }
      poly = out;
    }
    return { id: a.id, c: a.c, poly };
  });
};
