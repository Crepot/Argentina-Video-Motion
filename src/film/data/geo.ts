import { geo as geoV2 } from "../../atlas/south-atlantic-geometry";
import { catmullRomAt } from "../../paths/interpolate-path";
import type { Point } from "../../types/paths";

/**
 * Film-wide geography. One conformal (Mercator) projection for every map of
 * the film, registered on the V2 South Atlantic sheet: same longitude scale
 * (130.8 units/deg, 73°W on the 1978 stadium axis) and identical to V2's
 * local projection at the Malvinas latitude (51.7°S), so the final map and
 * the benchmark islands share one coordinate system.
 *
 * Coordinates are [lonW, latS] in degrees: West and South positive, East and
 * North negative. Outlines are simplified editorial polylines (storyboard §A
 * "Maps"), not survey data.
 */
export type LonLat = readonly [number, number];

const KX = 130.8;
const R = (KX * 180) / Math.PI;
const psi = (latS: number) => Math.log(Math.tan(Math.PI / 4 + (latS * Math.PI) / 360));
const REF_LAT = 51.7;
const REF_Y = geoV2(59, REF_LAT)[1];
const X0 = geoV2(73, 48.5)[0];

export const M = (lonW: number, latS: number): Point => [X0 + (73 - lonW) * KX, REF_Y + R * (psi(latS) - psi(REF_LAT))];
export const MP = (p: LonLat) => M(p[0], p[1]);

/** Smooth closed/open polyline → SVG path (world units). */
export const lonLatPath = (pts: readonly LonLat[], closed: boolean, sub = 3) => {
  const p = pts.map(MP);
  return smoothPath(p, closed, sub);
};

export const smoothPath = (p: readonly Point[], closed: boolean, sub = 3) => {
  const ring: Point[] = closed ? [p[p.length - 1], ...p, p[0], p[1]] : [p[0], ...p, p[p.length - 1]];
  const n = closed ? p.length : p.length - 1;
  let d = "";
  for (let i = 1; i <= n; i++) {
    for (let s = 0; s < sub; s++) {
      const q = catmullRomAt(ring, i + s / sub);
      d += `${d ? " L" : "M"} ${q[0].toFixed(1)} ${q[1].toFixed(1)}`;
    }
  }
  if (!closed) {
    const q = p[p.length - 1];
    d += ` L ${q[0].toFixed(1)} ${q[1].toFixed(1)}`;
  }
  return closed ? `${d} Z` : d;
};

